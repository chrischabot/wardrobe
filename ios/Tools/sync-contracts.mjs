// Copies the shared contracts into the Swift package.
//
//   node --experimental-strip-types ios/Tools/sync-contracts.mjs            write
//   node --experimental-strip-types ios/Tools/sync-contracts.mjs --check    exit 1 when stale
//
// The Swift contract types are produced by the foundation's generator
// (packages/contracts/scripts/generate.ts) from the zod schemas. This script calls the generator's
// pure entry point and writes its output, unmodified, to:
//   ios/GarderobeKit/Sources/GarderobeKit/Contracts/GarderobeContracts.swift
// so the app never carries a hand-written copy of a contract type. `--check` also reports whether the
// foundation's committed generated file differs from the live schemas (informational: that file is
// regenerated by the foundation workstream).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const { generate, SWIFT_PATH, SCHEMA_JSON_PATH } = await import(join(repo, "packages/contracts/scripts/generate.ts"));

const check = process.argv.includes("--check");
const generated = await generate();
// The generator returns `{ files, warnings }` (earlier revisions returned the array directly).
const files = Array.isArray(generated) ? generated : generated.files;
for (const warning of generated.warnings ?? []) console.error(`generator warning: ${warning}`);
const swift = files.find((f) => f.path === SWIFT_PATH);
const schema = files.find((f) => f.path === SCHEMA_JSON_PATH);
if (!swift || !schema) throw new Error("generator did not return the Swift and JSON Schema files");

const targets = [
  { path: join(repo, "ios/GarderobeKit/Sources/GarderobeKit/Contracts/GarderobeContracts.swift"), content: swift.content },
];

let stale = 0;
for (const t of targets) {
  const current = existsSync(t.path) ? readFileSync(t.path, "utf8") : undefined;
  const rel = t.path.slice(repo.length + 1);
  if (current === t.content) {
    console.log(`up to date  ${rel}`);
  } else if (check) {
    stale += 1;
    console.error(`out of date ${rel}`);
  } else {
    mkdirSync(dirname(t.path), { recursive: true });
    writeFileSync(t.path, t.content);
    console.log(`wrote       ${rel}`);
  }
}

const committed = join(repo, "packages/contracts", SWIFT_PATH);
const committedMatches = existsSync(committed) && readFileSync(committed, "utf8") === swift.content;
console.log(`foundation generated file ${committedMatches ? "matches" : "DIFFERS from"} the live schemas (packages/contracts/${SWIFT_PATH})`);

if (stale > 0) {
  console.error("The Swift contracts in ios/ are stale. Run: node --experimental-strip-types ios/Tools/sync-contracts.mjs");
  process.exitCode = 1;
}
