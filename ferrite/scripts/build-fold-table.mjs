// Writes src/fold_table.rs: what `normalizePhrase` (packages/domain/src/util.ts) makes of every non-ASCII
// code point on its own, NFKD, the combining marks U+0300 to U+036F dropped, lowercased, and every run of
// anything but `a-z`, `0-9` and `+` one separator, computed by Node's own `String.prototype.normalize`
// and `toLowerCase`, so the port never retypes Unicode data.
//
// Per code point is exact: NFKD of a string is the concatenation of each code point's decomposition,
// then a canonical reordering that moves only combining marks, none of which folds to `a-z`, `0-9` or
// `+`; and no character left after NFKD lowercases to ASCII through its context.
//
// Also writes tests/fixtures/normalize-phrases.json: phrases holding every code point of the table and
// seeded random code points from the whole of Unicode, each with `normalizePhrase`'s own result, which
// tests/wardrobe_reads.rs checks the port against.
//
//   node --experimental-strip-types ferrite/scripts/build-fold-table.mjs          # write
//   node --experimental-strip-types ferrite/scripts/build-fold-table.mjs --check  # exit 1 when stale
//
// Run from the wardrobe repository root (Node 22.6 or later).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const { normalizePhrase } = await import(path.join(repo, "packages/domain/src/util.ts"));

/** One code point through normalizePhrase's steps, its runs of separators kept as one space, not trimmed. */
function foldOne(cp) {
  return String.fromCodePoint(cp)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[\u2014\u2013]/g, "-")
    .replace(/[^a-z0-9+]+/g, " ");
}

// Every non-ASCII code point that folds to anything but one separator (the default).
const entries = [];
for (let cp = 0x80; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const folded = foldOne(cp);
  if (folded !== " ") entries.push([cp, folded]);
}

// Runs: consecutive code points with the same result (step 0), or each one ASCII letter or digit past
// the previous one's (step 1, as in the fullwidth and mathematical alphabets).
const next = (t) => (t.length === 1 && /[a-y0-8]/.test(t) ? String.fromCharCode(t.charCodeAt(0) + 1) : null);
const runs = [];
for (const [cp, text] of entries) {
  const last = runs[runs.length - 1];
  if (last && cp === last.end + 1) {
    if (last.step === 0 && text === last.text) {
      last.end = cp;
      continue;
    }
    const lastText = last.step === 1 ? String.fromCharCode(last.text.charCodeAt(0) + (last.end - last.start)) : last.text;
    // A one-entry run may become an advancing one; a run of repeats may not.
    if ((last.step === 1 || last.end === last.start) && next(lastText) === text) {
      last.step = 1;
      last.end = cp;
      continue;
    }
  }
  runs.push({ start: cp, end: cp, step: 0, text });
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const rust =
  "// @generated by ferrite/scripts/build-fold-table.mjs from Node's Unicode data; do not edit.\n" +
  `// Unicode ${process.versions.unicode}: ${entries.length} code points in ${runs.length} runs.\n` +
  "\n" +
  "/// `(first, last, step, text)`, sorted: each code point from `first` to `last` folds to `text` (step 0),\n" +
  "/// or to the one ASCII character `text` advanced by its distance from `first` (step 1). An empty `text`\n" +
  "/// is dropped; a space is a separator. A non-ASCII code point not listed is a separator.\n" +
  "pub(crate) static FOLD: &[(u32, u32, u8, &str)] = &[\n" +
  runs.map((r) => `    (${hex(r.start)}, ${hex(r.end)}, ${r.step}, ${JSON.stringify(r.text)}),\n`).join("") +
  "];\n";

// The fixture: every table code point, 40 to a phrase between ASCII words, then seeded random phrases.
let seed = 0x5eed1234;
const random = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 0x100000000;
};
const anyCodePoint = () => {
  for (;;) {
    const r = random();
    // Mostly the planes that hold letters, sometimes anywhere.
    const cp = r < 0.5 ? Math.floor(random() * 0x3000) : r < 0.8 ? Math.floor(random() * 0x10000) : Math.floor(random() * 0x110000);
    if (cp < 0xd800 || cp > 0xdfff) return cp;
  }
};
const words = ["Blue", "oxford", "PCF4339", "C++", "sock", "-", "  ", "'", "9", "Derby"];
const phrases = [];
for (let i = 0; i < entries.length; i += 40) {
  phrases.push(entries.slice(i, i + 40).map(([cp], j) => (j % 5 === 0 ? words[(i / 40 + j) % words.length] : "") + String.fromCodePoint(cp)).join(""));
}
for (let i = 0; i < 1500; i++) {
  let s = "";
  const n = 1 + Math.floor(random() * 12);
  for (let j = 0; j < n; j++) s += random() < 0.3 ? words[Math.floor(random() * words.length)] : String.fromCodePoint(random() < 0.5 ? entries[Math.floor(random() * entries.length)][0] : anyCodePoint());
  phrases.push(s);
}
phrases.push("ḃlue ⓑⓛⓤⓔ 𝐁𝐥𝐮𝐞 İstanbul ΣΟΦΟΣ Ⅻ ㎏ ½ ﬁt ＰＣＦ４３４０ 한국 👔 e\u0301\u0323");
const fixture = "[\n" + phrases.map((p) => `  ${JSON.stringify([p, normalizePhrase(p)])}`).join(",\n") + "\n]\n";

const outputs = [
  { file: path.join(repo, "ferrite/src/fold_table.rs"), text: rust },
  { file: path.join(repo, "ferrite/tests/fixtures/normalize-phrases.json"), text: fixture },
];
const summary = `${entries.length} code points in ${runs.length} runs (Unicode ${process.versions.unicode}), ${phrases.length} fixture phrases`;
if (process.argv.includes("--check")) {
  for (const { file, text } of outputs) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      current = "";
    }
    if (current !== text) {
      console.error(`${path.relative(repo, file)} is stale; run node --experimental-strip-types ferrite/scripts/build-fold-table.mjs`);
      process.exit(1);
    }
  }
  console.log(`fold table is up to date: ${summary}`);
} else {
  for (const { file, text } of outputs) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`wrote ferrite/src/fold_table.rs and ferrite/tests/fixtures/normalize-phrases.json: ${summary}`);
}
