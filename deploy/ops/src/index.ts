/** Two-step workflow with a durable sleep between the steps: the instance must survive its own suspension. */
export class OpsProbeWorkflow extends WorkflowEntrypoint<Env, { probeId: string }> {
  override async run(event: WorkflowEvent<{ probeId: string }>, step: WorkflowStep) {
    const started = await step.do("record start", async () => ({ probeId: event.payload.probeId, at: Date.now() }));
    await step.sleep("suspend", "5 seconds");
    return step.do("finish", async () => ({ ...started, resumedAfterMs: Date.now() - started.at }));
  }
}

async function authorized(request: Request, env: Env): Promise<boolean> {
  const token = /^Bearer\s+(.+)$/i.exec(request.headers.get("Authorization") ?? "")?.[1];
  if (!token || !env.OPS_TOKEN_SHA256) return false;
  const [a, b] = [await sha256(token), env.OPS_TOKEN_SHA256];
  let diff = a.length ^ b.length;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ (b.charCodeAt(i) || 0);
  return diff === 0;
}

