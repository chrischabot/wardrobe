/**
 * Seed. Resumable and idempotent: the importer's commands carry deterministic keys, so a call that ran
 * out of its per-invocation budget is simply called again and continues after replaying what is stored.
 */
async function seed(env: Env, body: { invite?: string[] }) {
  const db = env.DB;
  const userId = (await realOwner(env))?.user_id ?? (await createUser(db, { displayName: "Chris", isSynthetic: false })).userId;
  const service = new CommandService({ db, registry: createFoundationRegistry() });
  const result = await importOwnerData(service, importer(userId), { profileText, inventoryCsv });

  const syntheticId = (await syntheticOwner(env))?.user_id ?? (await createUser(db, { displayName: SYNTHETIC_OWNER, isSynthetic: true })).userId;
  for (let n = 1; n <= 3; n++) {
    await service.execute(importer(syntheticId), { type: "garment.create", payload: syntheticGarment(n, "Synthetic shirt"), idempotencyKey: `deploy-synthetic-garment:${n}`, expectedVersions: {}, authorization: "data_import", source: { channel: "import" } } as never);
  }
  const invitations: Record<string, string> = {};
  for (const who of body.invite ?? []) {
    if (who !== "owner" && who !== "synthetic") continue;
    invitations[who] = (await createInvitation(db, env, { userId: who === "owner" ? userId : syntheticId })).invitationCode;
  }
  return {
    complete: true,
    owner: { userId, receipts: result.receipts, replayed: result.replayed, conflicts: result.conflicts.length, profileSha256: result.profile.contentSha256 },
    synthetic: { userId: syntheticId },
    // One-time codes: returned to the deploy tooling's local state only, never written to evidence.
    invitations,
  };
}

/** What the import left in the database, as counts and one digest, for comparison with the local import. */
async function reconcile(env: Env) {
  const db = env.DB;
  const owner = await realOwner(env);
  if (!owner) return { seeded: false };
  const u = owner.user_id;
  const n = async (sql: string, ...params: unknown[]) => (await first<{ n: number }>(db, sql, ...params))?.n ?? 0;
  const rows = await all<{ name: string; category: string; units: number }>(
    db,
    `SELECT g.name, g.category, COALESCE((SELECT SUM(b.quantity) FROM stock_balances b WHERE b.user_id = g.user_id AND b.garment_id = g.garment_id AND b.bucket <> 'gone'), 0) AS units
     FROM garments g WHERE g.user_id = ? AND g.is_synthetic = 0 AND g.merged_into IS NULL AND g.removed_reason IS NULL ORDER BY g.name, g.category`,
    u,
  );
  const profile = await first<{ content_sha256: string }>(db, "SELECT content_sha256 FROM style_documents WHERE user_id = ? ORDER BY rowid LIMIT 1", u).catch(() => null);
  return {
    seeded: true,
    garments: rows.length,
    units: rows.reduce((sum, r) => sum + Number(r.units), 0),
    inventoryDigest: await sha256(rows.map((r) => `${r.name}|${r.category}|${r.units}`).join("\n")),
    profileSha256: profile?.content_sha256 ?? null,
    currentRules: await n("SELECT COUNT(*) AS n FROM style_rules WHERE user_id = ? AND is_current = 1", u),
    measurements: await n("SELECT COUNT(*) AS n FROM measurements WHERE user_id = ? AND superseded_by IS NULL", u),
    activeRestrictions: await n("SELECT COUNT(*) AS n FROM restrictions WHERE user_id = ? AND status = 'active'", u),
    wearObservations: await n("SELECT COUNT(*) AS n FROM wear_observations WHERE user_id = ?", u),
    laundryBatches: await n("SELECT COUNT(*) AS n FROM laundry_batches WHERE user_id = ?", u),
    importCommands: await n("SELECT COUNT(*) AS n FROM commands WHERE user_id = ? AND idempotency_key LIKE 'import:%'", u),
    syntheticOwners: await n("SELECT COUNT(*) AS n FROM users WHERE is_synthetic = 1"),
    linkedIdentities: await n("SELECT COUNT(*) AS n FROM auth_identities WHERE unlinked_at IS NULL"),
  };
}

