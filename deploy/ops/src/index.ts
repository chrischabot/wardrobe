export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    if (url.pathname === "/cdn-cgi/access/certs") return new Response(env.AUTO_JWKS_JSON, { headers: { "Content-Type": "application/json", "Cache-Control": "max-age=60" } });
    if (!url.pathname.startsWith("/ops/")) {
      // Local rehearsal only: this Worker stands in front of the product Worker in one local session.
      if (env.REHEARSAL === "1" && env.PRODUCT) return env.PRODUCT.fetch(request);
      return json({ error: "not_found" }, 404);
    }
    if (!(await authorized(request, env))) return json({ error: "unauthorized" }, 401);
    if (request.method !== "POST") return json({ error: "method_not_allowed" }, 405);
    const body = ((await request.json().catch(() => ({}))) ?? {}) as Record<string, unknown>;
    const started = Date.now();
    try {
      if (url.pathname === "/ops/seed") return json({ ...(await seed(env, body as { invite?: string[] })), ms: Date.now() - started });
      if (url.pathname === "/ops/reconcile") return json({ ...(await reconcile(env)), ms: Date.now() - started });
      const probe = /^\/ops\/probe\/([a-z0-9_]+)$/.exec(url.pathname)?.[1];
      if (probe && probes[probe]) return json({ probe, ...(await probes[probe](env, body)), ms: Date.now() - started });
      return json({ error: "not_found" }, 404);
    } catch (error) {
      // A failure is a result: the caller records it. `resumable` tells the seed loop to call again.
      return json({ ok: false, complete: false, resumable: true, error: brief(error), code: (error as { code?: string }).code ?? null, ms: Date.now() - started }, 200);
    }
  },
} satisfies ExportedHandler<Env>;
